/* The disc settle the debug monitor does around every raw file operation: wait
 * out the outstanding sceCdSync, then spin with an empty body. */
static inline void waitCd(void) /* derived name */
{
    int i;

    while (sceCdSync(1) != 0)
        ;
    i = 2000000;
    while (i--)
        ;
}

static void initLineTraceTable(void)
{
    int fd;
    int size;

    waitCd();
    sceFsReset();
    if ((fd = debugSceOpen("TRTABLE.BIN", 1)) < 0) {
        /* "cannot read the function-trace table file [%s]" */
        scePrintf("関数トレース用のテーブルファイル[\x1b[36m%s\x1b[m]が読めません。(0x%x)\n",
                  "TRTABLE.BIN", -fd);
        putString(0xFF000000, "No information.(\"%s\" can't read.)\n", "TRTABLE.BIN");
        return;
    }
    size = sceLseek(fd, 0, 2);
    waitCd();
    sceLseek(fd, 0, 0);
    waitCd();
    sceRead(fd, traceTable, size);
    traceTableNum = size / 8;
    scePrintf("Init line trace table. (\x1b[36mEntry: %ddatas\x1b[m)\n", traceTableNum);
    sceClose(fd);
    waitCd();
}

/* dispSource's TTY trace, built only when DEBUG is defined; the retail build
   does not define it, so the helper has no body there (the trace text
   derived). */
static __inline__ void debugExcDebugDisp(void) /* derived name */
{
#ifdef DEBUG
    scePrintf("dispSource\n");
#endif
}

/* What traceLine parses out of one TRFILE.TXT line and hands to dispSource:
   the code address, the byte offset of the source line, the frame size and
   the offset of the saved return address, read with the format at
   "%08x:%010d:%04x:%04x\n". */
typedef struct {       /* field names derived */
    unsigned int addr; /* 0x0 */
    int offset;        /* 0x4 */
    int stack;         /* 0x8 */
    int ra;            /* 0xC */
} SrcRef;              /* derived name */

/* Turns a code address into a source-line
   reference by binary-searching TRTABLE.BIN for the last entry at or below it,
   then reading the matching TRFILE.TXT line back for the report.  The 16-byte
   record goes back by value. */

static SrcRef traceLine(char *out, unsigned int addr)
{
    int pos = 0;
    int i = 0;
    int fd;
    int j;
    int n;
    char *src;
    SrcRef info = {-1, -1, -1, -1};
    unsigned char buf[1024];

    if (traceTable == 0) {
        putString(0xFF000000, "No information.(\"%s\" can't read.)\n", "TRTABLE.BIN");
        return info;
    }

    n = traceTableNum;
    for (; i < n; i++) {
        if (addr < traceTable[i].addr) {
            break;
        }
        pos = traceTable[i].pos;
    }

    waitCd();
    sceFsReset();

    if ((fd = debugSceOpen("TRFILE.TXT", 1)) < 0) {
        /* "cannot read the function-trace file [%s]" */
        scePrintf("関数トレースのファイル[\x1b[36m%s\x1b[m]が読めません。(0x%x)\n", "TRFILE.TXT",
                  -fd);

        putString(0xFF000000, "No information.(\"%s\" can't read.)\n", "TRFILE.TXT");

        return info;
    }

    waitCd();
    sceLseek(fd, pos, 0);
    waitCd();

    sceRead(fd, buf, 1024);

    for (j = 0; buf[j] != '\n'; j++)
        ;
    buf[j] = 0;

    sscanf((char *)buf, "%08x:%010d:%04x:%04x\n", &info.addr, &info.offset, &info.stack, &info.ra);
    /* The line's text starts past the 30-character "%08x:%010d:%04x:%04x\n"
       header the sscanf above just read. */
    src = (char *)&buf[30];
    info.addr = addr;
    info.stack = (short)info.stack;
    info.ra = (short)info.ra;
    scePrintf("%x:source Offset %d stack:%d ra:%d\n", info.addr, info.offset, info.stack, info.ra);
    scePrintf("0x%x: %s\n", info.addr, src);

    if (out != 0) {
        sprintf(out, "%s", src);
    }

    sceClose(fd);
    waitCd();

    return info;
}

/* inlined into display: eight rows of four {name, value} register pairs */
static inline void dispRegs(unsigned int *regs) /* derived name */
{
    int i;

    for (i = 0; i < 8; i++) {
        putString(0xFFFFFF00, "%s:%08x %s:%08x %s:%08x %s:%08x \n", regs[i * 8 + 1], regs[i * 8],
                  regs[i * 8 + 3], regs[i * 8 + 2], regs[i * 8 + 5], regs[i * 8 + 4],
                  regs[i * 8 + 7], regs[i * 8 + 6]);
    }
}

/* Prints the source lines around the faulting
   address: opens SRCFILE.TXT, reads a kilobyte at the offset traceLine found
   and walks it line by line, highlighting the one whose listing address
   matches.  The reference arrives by value.  The debugExcDebugDisp() call is
   the DEBUG-build TTY trace (see its definition above). */

static void dispSource(SrcRef ref, int lines)
{
    unsigned char buf[1024];
    char *line;
    int fd;
    int i;
    int n;
    int num;

    if (ref.offset < 0) {
        return;
    }

    waitCd();
    sceFsReset();

    if ((fd = debugSceOpen("SRCFILE.TXT", 1)) < 0) {
        /* "cannot read the source file [%s]" */
        scePrintf("ソースファイル[\x1b[36m%s\x1b[m]が読めません。(0x%x)\n", "SRCFILE.TXT", -fd);

        putString(0xFF000000, "No information.(\"%s\" can't read.)\n", "SRCFILE.TXT");

        return;
    }

    waitCd();
    sceLseek(fd, ref.offset, 0);
    waitCd();

    sceRead(fd, buf, 1024);
    buf[1023] = 0;

    line = (char *)buf;
    debugExcDebugDisp();
    n = 0;

    putString(0xFFFFFF00, " \n");
    for (i = 0; i < 1024; i++) {
        if (buf[i] == 0xA) {
            num = 0;

            buf[i] = 0;
            sscanf(line, "  %x:", &num);

            if (ref.addr == num) {
                *line = 0x87;
                putString(0x00FFFF00, "%s\n", line);
            } else {
                putString(0xFFFFFF00, "%s\n", line);
            }

            line = (char *)(&buf[i] + 1);
            if (++n >= lines) {
                break;
            }
        }
    }

    sceClose(fd);
    waitCd();
}

/* One page of the exception screen.  The second argument (cause) is never
   read.  `regs` is the flat
   {value, name} pair array regInfo, two words per EE register, so
   regs[62] is the saved ra and regs[58] the saved sp. */
static void display(int code, unsigned int cause, unsigned int epc, unsigned int badvaddr,
                    unsigned int status, unsigned int *regs, int page)
{
    unsigned char buf[1024];
    unsigned char buf2[1024];
    SrcRef info;
    SrcRef cur;
    unsigned int *p;
    unsigned int ra;
    unsigned int sp;
    int i;

    scePrintf("print phase: %d\n", page);
    debug_ClearFontWindow();

    putString(0xFFFFFF00, "IOS Reports Critical Error Message.\n");
    putString(0xFFFFFF00, "  %s\n", exceptionMessage);

    switch (page) {
    case 0:
        putString(0x40C0FF00, "%s\n", excTable[code].name);

        putString(0x40C0FF00, "  PC:%p BVA:%p BPA:%p\n", epc, badvaddr, status);

        dispRegs(regs);

        ra = regs[62] - 1;
        sp = regs[58];
        info = traceLine((char *)buf, epc);
        cur = info;
        scePrintf("stack:%p stackSize:%d raOffset:%d\n", sp, info.stack, info.ra);

        putString(0xFFFFFF00, "\205\n", buf);
        putString(0xFFFFFF00, "%s\n", buf);

        if (cur.stack >= 0 && cur.ra >= 0) {
            unsigned int r = *(unsigned int *)(sp + cur.ra);
            sp += cur.stack;
            cur = traceLine((char *)buf2, r - 1);
            putString(0xE0F0FF00, "\204%s\n", buf2);
        } else {
            cur = traceLine((char *)buf2, ra);
            putString(0xE0F0FF00, "\204%s\n", buf2);
        }

        if (cur.stack >= 0 && cur.ra >= 0) {
            unsigned int r = *(unsigned int *)(sp + cur.ra);
            sp += cur.stack;
            cur = traceLine((char *)buf2, r - 1);
            putString(0xB0D0F000, " \204%s\n", buf2);
        }

        if (cur.stack >= 0 && cur.ra >= 0) {
            unsigned int r = *(unsigned int *)(sp + cur.ra);
            sp += cur.stack;
            cur = traceLine((char *)buf2, r - 1);
            putString(0x80B0E000, "  \204%s\n", buf2);
        }

        if (cur.stack >= 0 && cur.ra >= 0) {
            unsigned int r = *(unsigned int *)(sp + cur.ra);
            sp += cur.stack;
            cur = traceLine((char *)buf2, r - 1);
            putString(0x5090D000, "   \204%s\n", buf2);
        }

        dispSource(info, 5);
        break;

    case 1:
        for (i = 0, p = regs; i < 16; i++, p += 2) {
            regQuad[0] = p[0];
            putString(0xFFFFFF00, "%s=%8.8x_%8.8x_%8.8x_%8.8x\n", p[1], regQuad[3], regQuad[2],
                      regQuad[1], regQuad[0]);
        }
        break;

    case 2:
        for (i = 0, p = regs + 32; i < 16; i++, p += 2) {
            regQuad[0] = p[0];
            putString(0xFFFFFF00, "%s=%8.8x_%8.8x_%8.8x_%8.8x\n", p[1], regQuad[3], regQuad[2],
                      regQuad[1], regQuad[0]);
        }
        break;
    }
}

