/* put the saved frame back on screen */
static inline void dispBack(int page, int tex) /* derived name */
{
    if (page != 0) {
        SetDrawnTextureEnvironment(0x4000);
    } else {
        SetDrawnTextureEnvironment(0x3000);
    }
    RestoreNormalDrawEnvironment(&db, buffer_ID, 0);
    drawSprite(128, 128, 128, 128, -320, -112, 320, 112, tex);
}

/* The EE exception handler the monitor installs
   for every trapped cause: freeze the game, copy the register image into the
   report window, draw the saved frame back over the screen and then loop on
   the pad, paging through the three report screens. */
static void debugEEExceptionMain(int arg0, unsigned int cause, unsigned int epc,
                                 unsigned int badvaddr, unsigned int status, EeReg128 *regs)
{
    int code = (cause >> 2) & 0xF;
    int sel = 0;
    int page;
    int tex;
    unsigned int i;
    unsigned int k;
    int spin;

    if (inException != 0) {
        return;
    }
    inException = 1;
    Emergency_DestroyAllThread();
    debugBackGroundDisableFlag = 1;

    scePrintf("called exception\n");

    /* the report starts on page 1, set inside the copy loop */
    for (i = 0; i < 32; i++) {
        regInfo[i * 2] = regs[i].w[0];
        page = 1;
    }

    /* a spin with an empty body, as in waitCd */
    spin = 1000000000;
    while (spin--)
        ;

    restoreSavedFrame();

    syncGS();

    initLineTraceTable();

    scePrintf("%s  (code = %d)\n", excTable[code].name, code);
    scePrintf("CAUSE %p\n", cause);
    scePrintf("EPC %p\n", epc);

    for (k = 0; k < 11; k++) {
        SetDebugHandler(excTable[k].code, 0);
    }

    iosPadEnable();

    resetPath();
    resetGS();

    clearDbgScreen();

    display(code, cause, epc, badvaddr, status, regInfo, 0);

    /* tex is set at the top of every pass, as page is inside the copy loop
       above */
    for (;;) {
        tex = 1;
        if (pad[0].flags & 0x20) {
            sel = page;
            if (sel >= 3) {
                sel = 0;
            }
            page = sel + 1;
            clearDbgScreen();
            if (sel != 0) {
                putString(0xFFFFFF00, "Frame buffer: %d\n", sel - 1);
            } else {
                display(code, cause, epc, badvaddr, status, regInfo, 0);
            }
        }

        if (sel != 0) {
            dispBack(sel - 1, tex);
        } else {
            dispBack(0, tex);
            saveBack();
        }

        baseFunc();
        syncGS();
        ExecKeyInput();
    }
}

inline void debugExceptionInit(void *workBuf)
{
    int i;

    traceTable = workBuf;
    scePrintf("num %d\n", sizeof(excTable) / sizeof(excTable[0]));
    for (i = 0; i < sizeof(excTable) / sizeof(excTable[0]); i++) {
        SetDebugHandler(excTable[i].code, debugEEExceptionMain);
    }
}

