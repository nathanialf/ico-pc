#!/usr/bin/env bash
# Regenerates rhi_test_spv.h (SPIR-V) and rhi_test_dxil.h (signed DXIL) from
# rhi_test.hlsl with DXC (the pinned release the shader toolchain uses;
# DXC=/path/to/dxc to pick one), and rhi_test_hlsl.h, the HLSL itself as a C
# string, which the Direct3D 11 backend's tests compile at run time with FXC
# (under ICO_D3D11 the file's REG macro drops the register spaces), and
# rhi_test_glsl.h, the GLSL the OpenGL backend's tests compile (each SPIR-V
# module through tools/spirv_to_glsl.py; SPIRV_CROSS=/path/to/spirv-cross to
# pick one; ps_subpass has none: GLSL cannot express an input attachment). The
# headers are committed so the RHI tests build without DXC.
#
# The -fvk-*-shift flags are the register-to-binding mapping the Vulkan
# backend expects (register number = RHI slot). DXIL is
# signed by the libdxil.so beside dxc; the [[vk::...]] attributes are ignored there, hence
# -Wno-ignored-attributes.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../../../.." && pwd)"
DXC="${DXC:-$ROOT/tools/toolchain/deps/dxc/bin/dxc}"
SPIRV_CROSS="${SPIRV_CROSS:-$ROOT/tools/toolchain/deps/spirv-cross/bin/spirv-cross}"
FLAGS=(-spirv -fspv-target-env=vulkan1.2 -fvk-b-shift 0 all -fvk-t-shift 16 all
       -fvk-s-shift 32 all -fvk-u-shift 48 all -O3)
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
for e in vs_main:vs_6_0 ps_dual:ps_6_0 ps_color:ps_6_0 ps_tex:ps_6_0 ps_uint:ps_6_0 \
         ps_depth_resolve:ps_6_0 ps_rov:ps_6_0 ps_subpass:ps_6_0; do
    "$DXC" "${FLAGS[@]}" -T "${e#*:}" -E "${e%%:*}" "$HERE/rhi_test.hlsl" -Fo "$TMP/${e%%:*}.spv"
    "$DXC" -O3 -Wno-ignored-attributes -T "${e#*:}" -E "${e%%:*}" "$HERE/rhi_test.hlsl" \
        -Fo "$TMP/${e%%:*}.dxil"
done
python3 - "$TMP" "$HERE/rhi_test_spv.h" "$("$DXC" --version 2>&1 | head -n 1)" <<'PY'
import struct, sys
tmp, out, ver = sys.argv[1], sys.argv[2], sys.argv[3]
names = ["vs_main", "ps_dual", "ps_color", "ps_tex", "ps_uint", "ps_depth_resolve",
         "ps_rov", "ps_subpass"]
lines = ["/* rhi_test_spv.h: generated by gen_shaders.sh from rhi_test.hlsl; do not edit.",
         " * " + ver.strip() + " */",
         "#ifndef PORT_RHI_TEST_RHI_TEST_SPV_H", "#define PORT_RHI_TEST_RHI_TEST_SPV_H", "",
         "#include <stdint.h>", ""]
for n in names:
    data = open(f"{tmp}/{n}.spv", "rb").read()
    words = struct.unpack(f"<{len(data)//4}I", data)
    lines.append(f"static const uint32_t spv_{n}[{len(words)}] = {{")
    for i in range(0, len(words), 6):
        lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i+6]) + ",")
    lines.append("};")
    lines.append("")
lines.append("#endif")
open(out, "w").write("\n".join(lines) + "\n")
PY
python3 - "$TMP" "$HERE/rhi_test_dxil.h" "$("$DXC" --version 2>&1 | head -n 1)" <<'PY'
import sys
tmp, out, ver = sys.argv[1], sys.argv[2], sys.argv[3]
names = ["vs_main", "ps_dual", "ps_color", "ps_tex", "ps_uint", "ps_depth_resolve",
         "ps_rov", "ps_subpass"]
lines = ["/* rhi_test_dxil.h: generated by gen_shaders.sh from rhi_test.hlsl; do not edit.",
         " * Signed DXIL (DXBC containers). " + ver.strip() + " */",
         "#ifndef PORT_RHI_TEST_RHI_TEST_DXIL_H", "#define PORT_RHI_TEST_RHI_TEST_DXIL_H", "",
         "#include <stdint.h>", ""]
for n in names:
    data = open(f"{tmp}/{n}.dxil", "rb").read()
    if data[:4] != b"DXBC" or data[4:20] == bytes(16):
        sys.exit(f"gen_shaders: {n}: unsigned or not a DXBC container")
    lines.append(f"static const uint8_t dxil_{n}[{len(data)}] = {{")
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i+12]) + ",")
    lines.append("};")
    lines.append("")
lines.append("#endif")
open(out, "w").write("\n".join(lines) + "\n")
PY
python3 - "$HERE/rhi_test.hlsl" "$HERE/rhi_test_hlsl.h" <<'PY'
import sys
src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
if "\0" in text or not text.endswith("\n"):
    sys.exit("gen_shaders: rhi_test.hlsl has a NUL or no final newline")
lines = ["/* rhi_test_hlsl.h: generated by gen_shaders.sh from rhi_test.hlsl; do not edit.",
         " * The HLSL text the Direct3D 11 tests compile at run time (FXC, ICO_D3D11=1). */",
         "#ifndef PORT_RHI_TEST_RHI_TEST_HLSL_H", "#define PORT_RHI_TEST_RHI_TEST_HLSL_H", "",
         "static const char rhi_test_hlsl[] ="]
for line in text.splitlines():
    esc = line.replace("\\", "\\\\").replace('"', '\\"')
    lines.append(f'    "{esc}\\n"')
lines[-1] += ";"
lines += ["", "#endif"]
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
PY
for e in vs_main ps_dual ps_color ps_tex ps_uint ps_depth_resolve ps_rov ps_subpass; do
    python3 -I "$ROOT/tools/spirv_to_glsl.py" --spirv-cross "$SPIRV_CROSS" --in "$TMP/$e.spv" \
        --out "$TMP/$e.glsl"
done
python3 - "$TMP" "$HERE/rhi_test_glsl.h" "$("$SPIRV_CROSS" --help 2>&1 | head -n 1 | sed "s/ Timestamp.*//")" <<'PY'
import sys
tmp, out, ver = sys.argv[1], sys.argv[2], sys.argv[3]
names = ["vs_main", "ps_dual", "ps_color", "ps_tex", "ps_uint", "ps_depth_resolve",
         "ps_rov", "ps_subpass"]
lines = ["/* rhi_test_glsl.h: generated by gen_shaders.sh from rhi_test_spv.h's modules with",
         " * tools/spirv_to_glsl.py (SPIRV-Cross " + ver.strip() + "); do not edit.",
         " * GLSL 4.30 text for the OpenGL backend's tests; ps_subpass is empty: GLSL cannot",
         " * express an input attachment. */",
         "#ifndef PORT_RHI_TEST_RHI_TEST_GLSL_H", "#define PORT_RHI_TEST_RHI_TEST_GLSL_H", ""]
for n in names:
    text = open(f"{tmp}/{n}.glsl", encoding="utf-8").read()
    if text and not text.startswith("#version 430"):
        sys.exit(f"gen_shaders: {n}: GLSL does not start with #version 430")
    if (n == "ps_subpass") != (text == ""):
        sys.exit(f"gen_shaders: {n}: only ps_subpass has no GLSL")
    if n == "ps_subpass":
        lines.append("/* ps_subpass: no GLSL (an input attachment) */")
    lines.append(f"static const char glsl_{n}[] =" + ("" if text else " \"\";"))
    parts = text.splitlines()
    for i, line in enumerate(parts):
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    "{esc}\\n"' + (";" if i == len(parts) - 1 else ""))
    lines.append("")
lines.append("#endif")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
PY
echo "wrote $HERE/rhi_test_spv.h, $HERE/rhi_test_dxil.h, $HERE/rhi_test_hlsl.h and $HERE/rhi_test_glsl.h"
