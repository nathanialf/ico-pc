/* rd_fixture_test: the fixture format on a frame built here (rd_fixture.h,
 * docs/port/TESTING_FIXTURES.md; CPU only, no dump from outside the tree).
 *
 * A small version 17 frame dump is written in memory with art filled by a
 * pseudo-random stream (a CPU-projected triangle, a shadow volume, a mesh, two
 * textures with GS levels, a text item, card verdicts and a facing table),
 * then: the fixture made from it; its check (no art); its expansion twice
 * (the same bytes, its SHA-256 pinned); the structure kept byte for byte (the
 * head, the lists but the VU draw's size without its cards, the sprite's
 * rectangle, the materials), the art generated by the rules (the alpha-tested
 * texture an alpha ramp, the additive one a bright patch, its GS level the
 * pattern at half size, the mesh's lattice at the size its matrix asks, the
 * strip flags from the index list, the shadow volume's front faces in front of
 * everything and its back faces behind, the text 'x', the card bytes and the
 * facing bits zero); the window check (no 32-byte window of the generated
 * bytes in the source's art); a fixture with art written into a generated
 * range or a changed pin refused; the file round trip with its notes; SHA-256
 * against FIPS 180-2's two short vectors; rd_fx_f32 on exact values.
 * argv[1]: a folder the test may write. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "rd_fixture.h"
#include "rd_mesh.h"

static int s_fail;
#define CHECK(c)                                                                                   \
    do {                                                                                           \
        if (!(c)) {                                                                                \
            fprintf(stderr, "%s:%d: CHECK(%s) failed\n", __FILE__, __LINE__, #c);                  \
            s_fail++;                                                                              \
        }                                                                                          \
    } while (0)

static uint32_t s_rng = 0x9E3779B9u;

static uint8_t art(void)
{
    s_rng ^= s_rng << 13;
    s_rng ^= s_rng >> 17;
    s_rng ^= s_rng << 5;
    return (uint8_t)(s_rng >> 11);
}

static void fillArt(uint8_t *p, size_t n)
{
    for (size_t i = 0; i < n; i++) {
        p[i] = art();
    }
}

static void putf(RdFxBuf *b, float f)
{
    uint32_t u;
    memcpy(&u, &f, 4);
    rd_fx_put32(b, u);
}

/* the frame's payload offsets */
enum {
    OFF_TRI = 0,                 /* RdScreenVtx[3]: art */
    OFF_RECT = OFF_TRI + 3 * 28, /* RdScreenVtx[2]: a sprite, structure */
    OFF_MESH = 256,              /* RdVuPayload + block + 1 material + 32 card bytes */
    OFF_SHADOW = OFF_MESH + 32 + 576 + 24 + 32, /* RdScreenVtx[6 + 6] */
    OFF_TEXT = OFF_SHADOW + 12 * 28,            /* RdTextItem */
    PAY_BYTES = OFF_TEXT + 304
};

static RdCmd cmd(uint8_t type)
{
    RdCmd c;
    memset(&c, 0, sizeof(c));
    c.type = type;
    return c;
}

/* the frame dump (version ver: 17, or 8 without the frame fields, the
 * region, the GS levels, the tick cameras and the facing tables, its state
 * blocks 84 bytes), into b; its art ranges filled from the stream; work2:
 * the list begins with WORK2 as the target (512 x 448), so the triangle
 * and the mesh are drawn into it */
static void buildDumpAt(RdFxBuf *b, uint32_t ver, bool work2)
{
    rd_fx_put(b, RD_DUMP_MAGIC, 8);
    rd_fx_put32(b, ver);
    rd_fx_put32(b, sizeof(RdCmd));
    rd_fx_put32(b, rd_fx_state_bytes(ver));
    rd_fx_put32(b, sizeof(RdScreenVtx));
    rd_fx_put32(b, 512);
    rd_fx_put32(b, 448);
    if (ver >= 10) {
        putf(b, 4.0f / 3.0f);
        putf(b, 512.0f);
        rd_fx_put32(b, 512);
    }
    char region[RD_DUMP_REGION_BYTES] = "pal";
    if (ver >= 12) {
        rd_fx_put(b, region, sizeof(region));
    }
    rd_fx_put32(b, 1);
    rd_fx_put32(b, 0);
    rd_fx_put32(b, 0);
    RdCamera cam;
    memset(&cam, 0, sizeof(cam));
    rd_fx_put(b, &cam, sizeof(cam));
    RdStateBlock st;
    memset(&st, 0, sizeof(st));
    st.gsW = 512;
    st.gsH = 448;
    rd_fx_put(b, &st, rd_fx_state_bytes(ver));
    rd_fx_put(b, &st, rd_fx_state_bytes(ver));
    /* list 0 */
    RdCmd c[16];
    int n = 0;
    if (work2) {
        c[n] = cmd(RDC_TARGET);
        c[n].u[0] = (uint32_t)RD_TARGET_WORK2 + 1u;
        c[n++].u[2] = 512u | (448u << 16);
    }
    c[n] = cmd(RDC_TEXTURE);
    c[n++].u[0] = 1;
    c[n] = cmd(RDC_TEST);
    c[n].b[0] = 1; /* ate */
    c[n].b[1] = 5; /* GEQUAL */
    c[n++].b[2] = 0x40;
    c[n] = cmd(RDC_SCREEN);
    c[n].b[0] = RD_PRIM_TRIANGLES;
    c[n].u[0] = OFF_TRI;
    c[n++].u[1] = 3;
    c[n] = cmd(RDC_SCREEN);
    c[n].b[0] = RD_PRIM_SPRITES;
    c[n].u[0] = OFF_RECT;
    c[n++].u[1] = 2;
    c[n] = cmd(RDC_TEST); /* the alpha test off, an additive blend */
    c[n++].b[1] = 1;
    c[n] = cmd(RDC_BLEND);
    c[n].b[0] = 0; /* Cs * FIX + Cd */
    c[n].b[1] = 0x80;
    c[n++].b[2] = 1;
    c[n] = cmd(RDC_TEXTURE);
    c[n++].u[0] = 2;
    c[n] = cmd(RDC_MESH);
    c[n].u[0] = 7;
    c[n].u[1] = OFF_MESH;
    c[n].keyLo = 1;
    c[n++].u[2] = 32 + 576 + 24 + 32;
    c[n] = cmd(RDC_SHADOW_STRIP);
    c[n].b[0] = RD_SHADOW_TRIS;
    c[n].u[0] = 6;
    c[n].u[1] = OFF_SHADOW;
    c[n].u[2] = 12 * 28;
    c[n++].u[3] = 6;
    c[n] = cmd(RDC_OVERLAY_TEXT);
    c[n].b[0] = RD_OTEXT_ITEM;
    c[n].u[1] = OFF_TEXT;
    c[n++].u[2] = sizeof(RdTextItem);
    rd_fx_put32(b, (uint32_t)n);
    rd_fx_put(b, c, sizeof(RdCmd) * (size_t)n);
    for (int l = 1; l < RD_LIST_COUNT; l++) {
        rd_fx_put32(b, 0);
    }
    /* the payload */
    uint8_t pay[PAY_BYTES];
    fillArt(pay, sizeof(pay));
    RdScreenVtx r[2];
    memset(r, 0, sizeof(r));
    r[0].x = (2048 - 256) * 16;
    r[0].y = (2048 - 224) * 16;
    r[1].x = (2048 + 256) * 16;
    r[1].y = (2048 + 224) * 16;
    r[1].q = r[0].q = 1.0f;
    memset(r[0].rgba, 0x80, 4);
    memset(r[1].rgba, 0x80, 4);
    memcpy(pay + OFF_RECT, r, sizeof(r));
    RdVuPayload h;
    memset(&h, 0, sizeof(h));
    h.code = 32;
    h.prog = 1;
    h.batchCount = 1;
    h.qwPerVertex = 3;
    h.materialCount = 1;
    memcpy(pay + OFF_MESH, &h, sizeof(h));
    /* mem[16..19]: x' = 2048 + 100 x, y' = 2048 + 100 y, w 1: a cube of half
       side 2^-2 reaches 25 pixels, the first of the powers of two to 24 */
    float m[4][4] = {{100, 0, 0, 0}, {0, 100, 0, 0}, {0, 0, 1, 0}, {2048, 2048, 0, 1}};
    memset(pay + OFF_MESH + 32, 0, 576);
    memcpy(pay + OFF_MESH + 32 + 16 * 16, m, sizeof(m));
    RdMaterial mat;
    memset(&mat, 0, sizeof(mat));
    mat.tex.id = 2;
    mat.blend = 4;
    memcpy(pay + OFF_MESH + 32 + 576, &mat, sizeof(mat));
    RdTextItem t;
    memset(&t, 0, sizeof(t));
    snprintf(t.utf8, sizeof(t.utf8), "HELLO");
    t.size = 16.0f;
    memcpy(pay + OFF_TEXT, &t, sizeof(t));
    rd_fx_put32(b, PAY_BYTES);
    rd_fx_put(b, pay, sizeof(pay));
    /* textures: 1 (8x4 RGBA8), 2 (16x16 RGBA8, two GS levels) */
    rd_fx_put32(b, 2);
    const uint32_t th[2][8] = {{1, RD_TEXKIND_IMAGE, 0, 0, 8, 4, 0, RD_TEXEL_RGBA8},
                               {2, RD_TEXKIND_IMAGE, 0, 0, 16, 16, 0, RD_TEXEL_RGBA8}};
    uint8_t px[16 * 16 * 4 + 8 * 8 * 4];
    for (int k = 0; k < 8; k++) {
        rd_fx_put32(b, th[0][k]);
    }
    fillArt(px, 8 * 4 * 4);
    rd_fx_put(b, px, 8 * 4 * 4);
    if (ver >= 9) {
        rd_fx_put32(b, 1);
    }
    for (int k = 0; k < 8; k++) {
        rd_fx_put32(b, th[1][k]);
    }
    fillArt(px, sizeof(px));
    rd_fx_put(b, px, 16 * 16 * 4);
    if (ver >= 9) {
        rd_fx_put32(b, 2);
        rd_fx_put(b, px + 16 * 16 * 4, 8 * 8 * 4);
    }
    rd_fx_put32(b, 0); /* temporary targets */
    /* mesh 7: 5 prelit vertices, one strip (kicks at 2, 3, 4) */
    rd_fx_put32(b, 1);
    const uint32_t mh[5] = {7, 5, 3, 9, 1};
    for (int k = 0; k < 5; k++) {
        rd_fx_put32(b, mh[k]);
    }
    char name[24] = "secret_name";
    rd_fx_put(b, name, 24);
    uint8_t stream[5 * 3 * 16];
    fillArt(stream, sizeof(stream));
    rd_fx_put(b, stream, sizeof(stream));
    for (uint32_t k = 2; k <= 4; k++) {
        for (uint32_t corner = 0; corner < 3; corner++) {
            rd_fx_put32(b, k * 4u + corner);
        }
    }
    RdVuBatchRec br;
    memset(&br, 0, sizeof(br));
    br.indexCount = 9;
    br.vertexCount = 5;
    rd_fx_put(b, &br, sizeof(br));
    if (ver >= 14) {
        rd_fx_put32(b, 0); /* no tick cameras */
        for (int k = 0; k < 32; k++) {
            rd_fx_put32(b, 0);
        }
    }
    if (ver >= 15) {
        rd_fx_put32(b, 1); /* one facing table */
        rd_fx_put32(b, 7);
        rd_fx_put32(b, 5);
        const uint8_t bits = 0x1F;
        rd_fx_put(b, &bits, 1);
    }
}

static void buildDump(RdFxBuf *b, uint32_t ver)
{
    buildDumpAt(b, ver, false);
}

/* the offset of the payload in a version ver dump with this frame's lists */
static size_t payloadAt(const uint8_t *d, uint32_t ver)
{
    size_t o = rd_fx_head_bytes(ver);
    for (int l = 0; l < RD_LIST_COUNT; l++) {
        const uint32_t n = rd_fx_get32(d + o);
        o += 4 + (size_t)n * sizeof(RdCmd);
    }
    return o + 4;
}

/* @water place's frame (version 17, 512 x 448): SCENE with FBA on drawn by
 * mesh 7 (the alpha bit's writer), a block 0x10015 (256 x 128, marked a block
 * in the temporary targets) drawn by mesh 8, then a triangle on SCENE with
 * ST and Q reading the block's texture 3 on REPEAT in S, CLAMP in T */
enum {
    WOFF_TRI = 0,               /* RdScreenVtx[3]: art */
    WOFF_MESH7 = 256,           /* RdVuPayload + block + 1 material + 32 card bytes */
    WOFF_MESH8 = 256 + 672,     /* the same */
    WPAY_BYTES = 256 + 2 * 672, /* 1600 */
    WBLOCK = 0x10015
};

static void putWaterMesh(uint8_t *pay, uint32_t off, float tx)
{
    RdVuPayload h;
    memset(&h, 0, sizeof(h));
    h.code = 32;
    h.prog = 1;
    h.batchCount = 1;
    h.qwPerVertex = 3;
    h.materialCount = 1;
    memcpy(pay + off, &h, sizeof(h));
    /* mem[16..19]: x' = tx + 100 x, y' = tx + 100 y, w 1 */
    float m[4][4] = {{100, 0, 0, 0}, {0, 100, 0, 0}, {0, 0, 1, 0}, {tx, tx, 0, 1}};
    memset(pay + off + 32, 0, 576);
    memcpy(pay + off + 32 + 16 * 16, m, sizeof(m));
    RdMaterial mat;
    memset(&mat, 0, sizeof(mat));
    mat.tex.id = 2;
    mat.blend = 4;
    memcpy(pay + off + 32 + 576, &mat, sizeof(mat));
}

static void buildWaterDump(RdFxBuf *b, bool block)
{
    const uint32_t ver = 17;
    rd_fx_put(b, RD_DUMP_MAGIC, 8);
    rd_fx_put32(b, ver);
    rd_fx_put32(b, sizeof(RdCmd));
    rd_fx_put32(b, rd_fx_state_bytes(ver));
    rd_fx_put32(b, sizeof(RdScreenVtx));
    rd_fx_put32(b, 512);
    rd_fx_put32(b, 448);
    putf(b, 4.0f / 3.0f);
    putf(b, 512.0f);
    rd_fx_put32(b, 512);
    char region[RD_DUMP_REGION_BYTES] = "pal";
    rd_fx_put(b, region, sizeof(region));
    rd_fx_put32(b, 1);
    rd_fx_put32(b, 0);
    rd_fx_put32(b, 0);
    RdCamera cam;
    memset(&cam, 0, sizeof(cam));
    rd_fx_put(b, &cam, sizeof(cam));
    RdStateBlock st;
    memset(&st, 0, sizeof(st));
    st.gsW = 512;
    st.gsH = 448;
    rd_fx_put(b, &st, rd_fx_state_bytes(ver));
    rd_fx_put(b, &st, rd_fx_state_bytes(ver));
    RdCmd c[16];
    int n = 0;
    c[n] = cmd(RDC_TARGET);
    c[n].u[0] = (uint32_t)RD_TARGET_SCENE + 1u;
    c[n++].u[2] = 512u | (448u << 16);
    c[n] = cmd(RDC_FBA);
    c[n++].b[0] = 1;
    c[n] = cmd(RDC_MESH);
    c[n].u[0] = 7;
    c[n].u[1] = WOFF_MESH7;
    c[n].keyLo = 1;
    c[n++].u[2] = 32 + 576 + 24 + 32;
    c[n] = cmd(RDC_FBA);
    c[n++].b[0] = 0;
    c[n] = cmd(RDC_TARGET);
    c[n].u[0] = WBLOCK;
    c[n++].u[2] = 256u | (128u << 16);
    c[n] = cmd(RDC_MESH);
    c[n].u[0] = 8;
    c[n].u[1] = WOFF_MESH8;
    c[n].keyLo = 2;
    c[n++].u[2] = 32 + 576 + 24 + 32;
    c[n] = cmd(RDC_TARGET);
    c[n].u[0] = (uint32_t)RD_TARGET_SCENE + 1u;
    c[n++].u[2] = 512u | (448u << 16);
    c[n] = cmd(RDC_TEXTURE);
    c[n].b[1] = 1;
    c[n++].u[0] = 3;
    c[n] = cmd(RDC_WRAP);
    c[n].b[0] = RD_WRAP_REPEAT;
    c[n++].b[1] = RD_WRAP_CLAMP;
    c[n] = cmd(RDC_SCREEN);
    c[n].b[0] = RD_PRIM_TRIANGLES;
    c[n].u[0] = WOFF_TRI;
    c[n++].u[1] = 3;
    rd_fx_put32(b, (uint32_t)n);
    rd_fx_put(b, c, sizeof(RdCmd) * (size_t)n);
    for (int l = 1; l < RD_LIST_COUNT; l++) {
        rd_fx_put32(b, 0);
    }
    uint8_t pay[WPAY_BYTES];
    fillArt(pay, sizeof(pay));
    /* mesh 7 about (1, 1) in model space lands on SCENE's middle (2048,
       2048); mesh 8 at the origin lands at (2048, 2048) */
    putWaterMesh(pay, WOFF_MESH7, 1948.0f);
    putWaterMesh(pay, WOFF_MESH8, 2048.0f);
    rd_fx_put32(b, WPAY_BYTES);
    rd_fx_put(b, pay, sizeof(pay));
    /* textures: 2 (16x16 RGBA8, one level), 3 (the block as a texture) */
    rd_fx_put32(b, 2);
    const uint32_t th[2][8] = {{2, RD_TEXKIND_IMAGE, 0, 0, 16, 16, 0, RD_TEXEL_RGBA8},
                               {3, RD_TEXKIND_TARGET, 0, 0, 256, 128, WBLOCK, 0}};
    uint8_t px[16 * 16 * 4];
    for (int k = 0; k < 8; k++) {
        rd_fx_put32(b, th[0][k]);
    }
    fillArt(px, sizeof(px));
    rd_fx_put(b, px, sizeof(px));
    rd_fx_put32(b, 1);
    for (int k = 0; k < 8; k++) {
        rd_fx_put32(b, th[1][k]);
    }
    /* the temporary target: the block (keep's bit 1), or a plain one */
    rd_fx_put32(b, 1);
    const uint32_t tt[5] = {WBLOCK, 256, 128, 1, block ? 2u : 0u};
    for (int k = 0; k < 5; k++) {
        rd_fx_put32(b, tt[k]);
    }
    /* meshes 7 and 8: 5 prelit vertices, one strip each */
    rd_fx_put32(b, 2);
    for (uint32_t id = 7; id <= 8; id++) {
        const uint32_t mh[5] = {id, 5, 3, 9, 1};
        for (int k = 0; k < 5; k++) {
            rd_fx_put32(b, mh[k]);
        }
        char name[24] = "secret_name";
        rd_fx_put(b, name, 24);
        uint8_t stream[5 * 3 * 16];
        fillArt(stream, sizeof(stream));
        rd_fx_put(b, stream, sizeof(stream));
        for (uint32_t k = 2; k <= 4; k++) {
            for (uint32_t corner = 0; corner < 3; corner++) {
                rd_fx_put32(b, k * 4u + corner);
            }
        }
        RdVuBatchRec br;
        memset(&br, 0, sizeof(br));
        br.indexCount = 9;
        br.vertexCount = 5;
        rd_fx_put(b, &br, sizeof(br));
    }
    rd_fx_put32(b, 0); /* no tick cameras */
    for (int k = 0; k < 32; k++) {
        rd_fx_put32(b, 0);
    }
    rd_fx_put32(b, 0); /* no facing tables */
}

static uint32_t fbits(float f)
{
    uint32_t u;
    memcpy(&u, &f, 4);
    return u;
}

int main(int argc, char **argv)
{
    /* SHA-256: FIPS 180-2's "abc" and the empty message */
    uint8_t sha[32];
    char hex[65];
    rd_fx_sha256("abc", 3, sha);
    rd_fx_sha_hex(sha, hex);
    CHECK(strcmp(hex, "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad") == 0);
    rd_fx_sha256("", 0, sha);
    rd_fx_sha_hex(sha, hex);
    CHECK(strcmp(hex, "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855") == 0);
    /* 56 bytes: the length in a second block */
    rd_fx_sha256("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq", 56, sha);
    rd_fx_sha_hex(sha, hex);
    CHECK(strcmp(hex, "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1") == 0);
    /* the float bits */
    CHECK(rd_fx_f32(1, 0) == fbits(1.0f));
    CHECK(rd_fx_f32(-8, -5) == fbits(-0.25f));
    CHECK(rd_fx_f32(127, 0) == fbits(127.0f));
    CHECK(rd_fx_f32(3, -4) == fbits(0.1875f));
    CHECK(rd_fx_f32(0xFFFFFF, 8) == fbits(4294967040.0f));
    CHECK(rd_fx_f32(0, 3) == 0u);

    RdFxBuf d = {0};
    buildDump(&d, 17);
    CHECK(!d.bad);
    RdFixture fx;
    char why[512] = "", report[1024] = "";
    const bool made =
        rd_fixture_make(d.p, d.n, NULL, &fx, report, sizeof(report), why, sizeof(why));
    CHECK(made);
    if (!made) {
        fprintf(stderr, "make: %s\n", why);
        return 1;
    }
    printf("%s\n", report);
    char stats[512] = "";
    CHECK(rd_fixture_check(&fx, why, sizeof(why), stats, sizeof(stats)));
    printf("check: %s %s\n", stats, why);

    uint8_t *x = NULL, *y = NULL;
    size_t xn = 0, yn = 0;
    CHECK(rd_fixture_expand(&fx, true, &x, &xn, why, sizeof(why)));
    CHECK(rd_fixture_expand(&fx, true, &y, &yn, why, sizeof(why)));
    CHECK(x && y && xn == yn && memcmp(x, y, xn) == 0 && xn == fx.expandedBytes);
    CHECK(xn == d.n); /* every art array its source's size */
    free(y);
    if (!x) {
        return 1;
    }
    /* the structure as the dump's: the head, the lists but the mesh's size */
    const size_t head = rd_fx_head_bytes(17);
    CHECK(memcmp(x, d.p, head) == 0);
    const size_t px = payloadAt(x, 17), pd = payloadAt(d.p, 17);
    CHECK(px == pd);
    RdCmd mesh;
    memcpy(&mesh, x + head + 4 + 7 * sizeof(RdCmd), sizeof(mesh));
    CHECK(mesh.type == RDC_MESH && mesh.u[2] == 32u + 576u + 24u);
    CHECK(memcmp(x + px + OFF_RECT, d.p + pd + OFF_RECT, 2 * 28) == 0);
    CHECK(memcmp(x + px + OFF_MESH, d.p + pd + OFF_MESH, 32 + 576 + 24) == 0);
    /* the card verdicts dropped: zero */
    for (int i = 0; i < 32; i++) {
        CHECK(x[px + OFF_MESH + 632 + (size_t)i] == 0);
    }
    /* the text */
    CHECK(memcmp(x + px + OFF_TEXT, "xxxxx", 6) == 0);
    CHECK(memcmp(x + px + OFF_TEXT + 256, d.p + pd + OFF_TEXT + 256, 304 - 256) == 0);
    /* the triangle generated: in the middle half, in front, grey */
    RdScreenVtx v;
    memcpy(&v, x + px + OFF_TRI, sizeof(v));
    CHECK(v.x == (2048 - 256 + 128) * 16 && v.y == (2048 - 224 + 112) * 16);
    CHECK(v.z == 0xFFFFFFFFu && v.rgba[0] == 128 && v.q == 1.0f);
    /* the shadow volume: 2 front triangles at the farthest Z (always
       passing GEQUAL), 2 back ones at 0, tagged 1..4 */
    for (int i = 0; i < 12; i++) {
        memcpy(&v, x + px + OFF_SHADOW + (size_t)i * 28, sizeof(v));
        CHECK(v.z == (i < 6 ? 0xFFFFFFFFu : 0u));
        CHECK(v.rgba[0] == (uint8_t)(i / 3 + 1));
        /* the footprint: 128 x 112 pixels from (128, 168) (the middle less
           two sixteenths of the width: the first shadow command) */
        CHECK(v.x >= (2048 - 256 + 128) * 16 && v.x <= (2048 - 256 + 256) * 16);
        CHECK(v.y >= (2048 - 224 + 168) * 16 && v.y <= (2048 - 224 + 280) * 16);
    }
    /* the textures: after the payload, the count, then texture 1's header */
    size_t o = px + PAY_BYTES;
    CHECK(rd_fx_get32(x + o) == 2);
    o += 4 + 32;
    /* texture 1 was drawn with the alpha test on: the alpha ramp */
    CHECK(x[o + 3] == 0 && x[o + 7 * 4 + 3] == 255 && x[o + 0] == 160);
    o += 8 * 4 * 4;
    CHECK(rd_fx_get32(x + o) == 1);
    o += 4 + 32;
    /* texture 2 with an additive blend: the bright patch; its GS level the
       pattern at 8 x 8 */
    CHECK(x[o] == 32 && x[o + (8 * 16 + 8) * 4] == 255 && x[o + 3] == 128);
    o += 16 * 16 * 4;
    CHECK(rd_fx_get32(x + o) == 2);
    o += 4;
    CHECK(x[o] == 32 && x[o + (4 * 8 + 4) * 4] == 255 && x[o + (2 * 8 + 1) * 4] == 32);
    o += 8 * 8 * 4;
    CHECK(rd_fx_get32(x + o) == 0); /* temps */
    o += 4;
    CHECK(rd_fx_get32(x + o) == 1); /* meshes */
    o += 4 + 20;
    CHECK(memcmp(x + o, "m0001\0", 6) == 0);
    o += 24;
    /* the lattice at 2^-2 (step 2^-5): vertex 0 at (-0.25, -0.25, -0.25), its
       strip flag set (ST.w 0), vertex 1 one step up, vertex 2 kicked
       (ST.w 1), colour (112, 120, 136, 127) */
    CHECK(rd_fx_get32(x + o) == fbits(-0.25f) && rd_fx_get32(x + o + 4) == fbits(-0.25f));
    CHECK(rd_fx_get32(x + o + 12) == fbits(1.0f));
    CHECK(rd_fx_get32(x + o + 16 + 12) == 0u);
    CHECK(rd_fx_get32(x + o + 48 + 4) == fbits(-0.25f + 0.03125f));
    CHECK(rd_fx_get32(x + o + 96 + 16 + 12) == fbits(1.0f));
    CHECK(rd_fx_get32(x + o + 32) == fbits(112.0f) && rd_fx_get32(x + o + 44) == fbits(127.0f));
    o += 5 * 3 * 16 + 9 * 4 + sizeof(RdVuBatchRec) + 4 + 128;
    CHECK(rd_fx_get32(x + o) == 1 && rd_fx_get32(x + o + 4) == 7 && x[o + 12] == 0);
    CHECK(o + 13 == xn);

    /* the window check: none of the generated windows is in the source's art */
    uint64_t windows = 0, hits = 0;
    CHECK(rd_fixture_selfcheck(d.p, d.n, x, xn, &windows, &hits, why, sizeof(why)));
    printf("window check: %llu of %llu windows found\n", (unsigned long long)hits,
           (unsigned long long)windows);
    CHECK(windows > 0 && hits == 0);
    /* and the check finds a source's own window in itself */
    CHECK(rd_fixture_selfcheck(d.p, d.n, d.p, d.n, &windows, &hits, why, sizeof(why)));
    CHECK(hits > 0 && hits == windows);
    free(x);

    /* the file round trip, with the notes */
    CHECK(rd_fixture_add_note(&fx, "expect", "shadow_volume_draws>=1"));
    char path[1024];
    snprintf(path, sizeof(path), "%s/rd_fixture_test.rdfix", argc > 1 ? argv[1] : ".");
    CHECK(rd_fixture_write(path, &fx, why, sizeof(why)));
    RdFixture back;
    CHECK(rd_fixture_read(path, &back, why, sizeof(why)));
    CHECK(back.skelBytes == fx.skelBytes && memcmp(back.skel, fx.skel, fx.skelBytes) == 0);
    CHECK(memcmp(back.sha, fx.sha, 32) == 0 && back.noteCount == fx.noteCount);
    CHECK(rd_fixture_note(&back, "expect") &&
          strcmp(rd_fixture_note(&back, "expect"), "shadow_volume_draws>=1") == 0);
    CHECK(rd_fixture_note(&back, "rule") && rd_fixture_note(&back, "maker"));
    rd_fixture_free(&back);

    /* art written into a generated range: refused by the check */
    const size_t skelPay = payloadAt(fx.skel, 17);
    fx.skel[skelPay + OFF_TRI + 5] = 0x5A;
    CHECK(!rd_fixture_check(&fx, why, sizeof(why), NULL, 0));
    printf("refused as expected: %s\n", why);
    fx.skel[skelPay + OFF_TRI + 5] = 0;
    CHECK(rd_fixture_check(&fx, why, sizeof(why), NULL, 0));
    /* a changed pin: refused by the expansion */
    fx.sha[0] ^= 1;
    CHECK(!rd_fixture_expand(&fx, true, &x, &xn, why, sizeof(why)));
    printf("refused as expected: %s\n", why);
    rd_fixture_free(&fx);
    rd_fx_free(&d);

    /* a version 8 dump (no frame fields, region, GS levels, tick cameras or
       facing tables; 84-byte state blocks): made, checked, expanded to its
       pin at its own layout and size, the structure kept, the art generated */
    RdFxBuf d8 = {0};
    buildDump(&d8, 8);
    CHECK(rd_fixture_make(d8.p, d8.n, NULL, &fx, report, sizeof(report), why, sizeof(why)));
    printf("version 8: %s %s\n", report, why);
    CHECK(fx.dumpVersion == 8);
    CHECK(rd_fixture_check(&fx, why, sizeof(why), NULL, 0));
    x = NULL;
    CHECK(rd_fixture_expand(&fx, true, &x, &xn, why, sizeof(why)));
    if (x) {
        const size_t h8 = rd_fx_head_bytes(8), p8 = payloadAt(x, 8);
        CHECK(h8 == rd_fx_head_bytes(17) - 12 - RD_DUMP_REGION_BYTES - 8);
        CHECK(xn == d8.n && memcmp(x, d8.p, h8) == 0 && p8 == payloadAt(d8.p, 8));
        CHECK(memcmp(x + p8 + OFF_RECT, d8.p + p8 + OFF_RECT, 2 * 28) == 0);
        CHECK(memcmp(x + p8 + OFF_TEXT, "xxxxx", 6) == 0);
        /* texture 1's alpha ramp right after the payload's texture header */
        const size_t t8 = p8 + PAY_BYTES + 4 + 32;
        CHECK(x[t8 + 3] == 0 && x[t8 + 7 * 4 + 3] == 255);
        CHECK(rd_fixture_selfcheck(d8.p, d8.n, x, xn, &windows, &hits, why, sizeof(why)));
        CHECK(windows > 0 && hits == 0);
        free(x);
    }
    rd_fixture_free(&fx);
    rd_fx_free(&d8);

    /* the placement rules (rd_fixture.h): the frame with WORK2 as the target */
    static const char placeRules[] = "alpha_ramp ate\nbright additive\nchecker\n"
                                     "@lamps place\n@fans off\n";
    RdFxBuf dw = {0};
    buildDumpAt(&dw, 17, true);
    CHECK(!dw.bad);
    /* without the rules: no section, the mesh about its origin as above */
    CHECK(rd_fixture_make(dw.p, dw.n, NULL, &fx, report, sizeof(report), why, sizeof(why)));
    const size_t plainSkel = fx.skelBytes;
    x = NULL;
    CHECK(rd_fixture_expand(&fx, true, &x, &xn, why, sizeof(why)));
    if (x) {
        const size_t pw = payloadAt(x, 17);
        memcpy(&v, x + pw + OFF_TRI, sizeof(v));
        CHECK(v.x == (2048 - 256 + 128) * 16);
        size_t ow = pw + PAY_BYTES + 4 + 32 + 8 * 4 * 4 + 4 + 32 + 16 * 16 * 4 + 4 + 8 * 8 * 4;
        ow += 4 + 4 + 20 + 24;
        CHECK(rd_fx_get32(x + ow) == fbits(-0.25f) && rd_fx_get32(x + ow + 4) == fbits(-0.25f));
        free(x);
    }
    rd_fixture_free(&fx);
    /* with them: mesh 7 is the first mesh drawn into WORK2, so its place is
       the scissor's first inner column and row: X = 2048 - 256 + 512 / 4 =
       1920, Y = 2048 - 224 + 448 / 4 = 1936; the matrix has no perspective,
       so the centre is the point of that line nearest the origin, (-1.28,
       -1.12, 0); the size there 2^-2 as at the origin (25 pixels), the
       lattice step 2^-5: the centre (-41, -36, 0) steps, vertex 0 at
       ((-41 - 8) / 32, (-36 - 8) / 32, -8 / 32); the triangle 8 GS pixels
       past the target's right edge */
    CHECK(rd_fixture_make(dw.p, dw.n, placeRules, &fx, report, sizeof(report), why, sizeof(why)));
    printf("placement: %s %s\n", report, why);
    CHECK(strstr(report, "1 meshes drawn into WORK2 generated on it (0 kept their origin), 1 "
                         "prims drawn into WORK2 generated beside it") != NULL);
    CHECK(fx.skelBytes == plainSkel + 4 + 4 + 16 + 4 + 4);
    CHECK(rd_fx_get32(fx.skel + plainSkel) == RD_FX_PLACE_TAG);
    CHECK(rd_fx_get32(fx.skel + plainSkel + 8) == 7 &&
          (int32_t)rd_fx_get32(fx.skel + plainSkel + 12) == -41 &&
          (int32_t)rd_fx_get32(fx.skel + plainSkel + 16) == -36 &&
          rd_fx_get32(fx.skel + plainSkel + 20) == 0);
    CHECK(rd_fx_get32(fx.skel + plainSkel + 28) == OFF_TRI);
    CHECK(rd_fixture_check(&fx, why, sizeof(why), stats, sizeof(stats)));
    CHECK(strstr(stats, "1 meshes placed on WORK2, 1 prims beside it") != NULL);
    x = NULL;
    CHECK(rd_fixture_expand(&fx, true, &x, &xn, why, sizeof(why)));
    if (x) {
        const size_t pw = payloadAt(x, 17);
        CHECK(xn == dw.n);
        memcpy(&v, x + pw + OFF_TRI, sizeof(v));
        CHECK(v.x == (2048 - 256 + 512 + 8) * 16 && v.y == (2048 - 224 + 112) * 16);
        size_t ow = pw + PAY_BYTES + 4 + 32 + 8 * 4 * 4 + 4 + 32 + 16 * 16 * 4 + 4 + 8 * 8 * 4;
        ow += 4 + 4 + 20 + 24;
        CHECK(rd_fx_get32(x + ow) == fbits(-49.0f / 32.0f));
        CHECK(rd_fx_get32(x + ow + 4) == fbits(-44.0f / 32.0f));
        CHECK(rd_fx_get32(x + ow + 8) == fbits(-0.25f) && rd_fx_get32(x + ow + 12) == fbits(1.0f));
        CHECK(rd_fixture_selfcheck(dw.p, dw.n, x, xn, &windows, &hits, why, sizeof(why)));
        CHECK(windows > 0 && hits == 0);
        free(x);
    }
    /* a cut or empty section does not parse */
    fx.skelBytes -= 4;
    CHECK(!rd_fixture_check(&fx, why, sizeof(why), NULL, 0));
    fx.skelBytes += 4;
    rd_fixture_free(&fx);
    rd_fx_free(&dw);
    /* the rules on a frame that draws nothing into WORK2: refused; a
       placement line that is not one: refused */
    RdFxBuf dn = {0};
    buildDump(&dn, 17);
    CHECK(!rd_fixture_make(dn.p, dn.n, placeRules, &fx, report, sizeof(report), why, sizeof(why)));
    CHECK(strstr(why, "matched nothing") != NULL);
    CHECK(!rd_fixture_make(dn.p, dn.n, "checker\n@lamps move\n", &fx, report, sizeof(report), why,
                           sizeof(why)));
    rd_fx_free(&dn);
    /* @water place (rd_fixture.h).  Mesh 7, the first mesh drawn into SCENE
       with FBA on, takes grid point (0 + 4) mod 9 = 4, the scissor's middle:
       X = 2048 - 256 + 512 * 2 / 4 = 2048, Y = 2048 - 224 + 448 * 2 / 4 =
       2048; its matrix x' = 1948 + 100 x has no perspective, so the centre is
       the point of that line nearest the origin, (1, 1, 0); the size 2^-2
       (25 pixels), the lattice step 2^-5: (32, 32, 0) steps, vertex 0 at
       ((32 - 8) / 32, (32 - 8) / 32, -8 / 32).  Mesh 8, the first drawn into
       the block (256 x 128), takes the block's first inner column and row:
       X = 2048 - 128 + 256 / 4 = 1984, Y = 2048 - 64 + 128 / 4 = 2016, so
       (-0.64, -0.32, 0): (-20, -10, 0) steps (-20.48 and -10.24 rounded).
       The triangle reads the block on REPEAT in S only: S from 12 / 16 by
       sixteenths along the ribbon's columns, T as before (0, then 1) */
    static const char waterRules[] = "alpha_ramp ate\nchecker\n@water place\n";
    RdFxBuf dwa = {0};
    buildWaterDump(&dwa, true);
    CHECK(!dwa.bad);
    CHECK(rd_fixture_make(dwa.p, dwa.n, NULL, &fx, report, sizeof(report), why, sizeof(why)));
    const size_t waterPlain = fx.skelBytes;
    rd_fixture_free(&fx);
    CHECK(rd_fixture_make(dwa.p, dwa.n, waterRules, &fx, report, sizeof(report), why, sizeof(why)));
    printf("water placement: %s %s\n", report, why);
    CHECK(strstr(report, "water: 1 meshes drawn into a block generated on it, 1 meshes setting "
                         "SCENE's alpha bit generated on SCENE (0 kept their origin), 1 prims "
                         "reading a block generated across its period") != NULL);
    CHECK(fx.skelBytes == waterPlain + 4 + 4 + 2 * 16 + 4 + 4 + 8);
    CHECK(rd_fx_get32(fx.skel + waterPlain) == RD_FX_PLACE_TAG3);
    CHECK(rd_fx_get32(fx.skel + waterPlain + 4) == 2);
    CHECK(rd_fx_get32(fx.skel + waterPlain + 8) == 7 &&
          (int32_t)rd_fx_get32(fx.skel + waterPlain + 12) == 32 &&
          (int32_t)rd_fx_get32(fx.skel + waterPlain + 16) == 32 &&
          rd_fx_get32(fx.skel + waterPlain + 20) == 0);
    CHECK(rd_fx_get32(fx.skel + waterPlain + 24) == 8 &&
          (int32_t)rd_fx_get32(fx.skel + waterPlain + 28) == -20 &&
          (int32_t)rd_fx_get32(fx.skel + waterPlain + 32) == -10 &&
          rd_fx_get32(fx.skel + waterPlain + 36) == 0);
    CHECK(rd_fx_get32(fx.skel + waterPlain + 40) == 0); /* no prim beside WORK2 */
    CHECK(rd_fx_get32(fx.skel + waterPlain + 44) == 1 &&
          rd_fx_get32(fx.skel + waterPlain + 48) == WOFF_TRI &&
          rd_fx_get32(fx.skel + waterPlain + 52) == RD_FX_ACROSS_S);
    CHECK(rd_fixture_check(&fx, why, sizeof(why), stats, sizeof(stats)));
    CHECK(strstr(stats, "2 meshes placed on a block or SCENE, 0 prims beside WORK2, 1 prims read "
                        "across a block's period") != NULL);
    x = NULL;
    CHECK(rd_fixture_expand(&fx, true, &x, &xn, why, sizeof(why)));
    if (x) {
        const size_t pw = payloadAt(x, 17);
        CHECK(xn == dwa.n);
        RdScreenVtx w[3];
        memcpy(w, x + pw + WOFF_TRI, sizeof(w));
        CHECK(w[0].x == (2048 - 256 + 128) * 16 && w[0].y == (2048 - 224 + 112) * 16);
        CHECK(w[0].s == 0.75f && w[0].t == 0.0f);
        CHECK(w[1].s == 0.75f && w[1].t == 1.0f && w[1].y == (2048 - 224 + 140) * 16);
        CHECK(w[2].s == 0.8125f && w[2].t == 0.0f && w[2].x == (2048 - 256 + 144) * 16);
        /* mesh 7's first vertex: after the payload, the two textures (the
           image's header, texels and level count; the target's header), the
           temporary target and mesh 7's header and name */
        size_t ow = pw + WPAY_BYTES + 4 + 32 + 16 * 16 * 4 + 4 + 32 + 4 + 20 + 4 + 20 + 24;
        CHECK(rd_fx_get32(x + ow) == fbits(0.75f) && rd_fx_get32(x + ow + 4) == fbits(0.75f));
        CHECK(rd_fx_get32(x + ow + 8) == fbits(-0.25f));
        /* mesh 8's: after mesh 7's stream, index list and batch */
        ow += 5 * 3 * 16 + 9 * 4 + sizeof(RdVuBatchRec) + 20 + 24;
        CHECK(rd_fx_get32(x + ow) == fbits(-28.0f / 32.0f) &&
              rd_fx_get32(x + ow + 4) == fbits(-18.0f / 32.0f));
        CHECK(rd_fixture_selfcheck(dwa.p, dwa.n, x, xn, &windows, &hits, why, sizeof(why)));
        CHECK(windows > 0 && hits == 0);
        free(x);
    }
    /* a cut section does not parse */
    fx.skelBytes -= 4;
    CHECK(!rd_fixture_check(&fx, why, sizeof(why), NULL, 0));
    fx.skelBytes += 4;
    rd_fixture_free(&fx);
    rd_fx_free(&dwa);
    /* the same frame whose temporary target is not marked a block: refused */
    RdFxBuf dnb = {0};
    buildWaterDump(&dnb, false);
    CHECK(
        !rd_fixture_make(dnb.p, dnb.n, waterRules, &fx, report, sizeof(report), why, sizeof(why)));
    CHECK(strstr(why, "matched nothing") != NULL);
    rd_fx_free(&dnb);
    printf("rd_fixture_test: %s\n", s_fail ? "FAILED" : "all passed");
    return s_fail ? 1 : 0;
}
